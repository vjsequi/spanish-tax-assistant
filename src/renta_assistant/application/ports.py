"""Interfaces implemented by local adapters and later by hosted adapters."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from renta_assistant.domain.calculation import Fact, Policy


class CaseSources(Protocol):
    def case(self, case_id: str) -> dict[str, Any]: ...
    def document(self, case_id: str, document_id: str) -> Path: ...
    def candidates(self) -> dict[str, Fact]: ...
    def draft(self) -> dict[str, str]: ...
    def policy(self) -> Policy: ...
    def references(self) -> list[dict[str, str]]: ...


class StateStore(Protocol):
    def load(self) -> dict[str, Any] | None: ...
    def save(self, data: dict[str, Any]) -> None: ...
